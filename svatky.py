def popis_dne(kdy=None):
    """
    Vrátí řádek do hlavičky přihlašovací stránky, například:

        "neděle 30. srpna · Vladena"
        "úterý 24. prosince · Štědrý den · Adam a Eva"
        "středa 28. října · Vznik samostatného státu"

    Když je den státní svátek, jeho název jde první - je to podstatnější
    než jmeniny. Jmeniny se připojí za něj, pokud nějaké jsou.
    """
    kdy = kdy or date.today()
    klic = f"{kdy.month:02d}-{kdy.day:02d}"

    datum = f"{DNY[kdy.weekday()]} {kdy.day}. {MESICE[kdy.month - 1]}"

    svatek = SVATKY_STATNI.get(klic)
    jmeno = None if klic in OPRAVY_BEZ_JMENA else JMENINY.get(klic)

    # Když se název svátku a jmeniny kryjí (5. 7. Cyril a Metoděj),
    # nepsat to dvakrát.
    if svatek and jmeno and jmeno in svatek:
        jmeno = None

    return " · ".join(c for c in (datum, svatek, jmeno) if c)
